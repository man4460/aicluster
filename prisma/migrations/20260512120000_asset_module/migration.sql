  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `ast_asset_owner_trial_code_uidx` (`owner_id`, `trial_session_id`, `asset_code`),
