CREATE TABLE `asset_transactions` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `owner_id` VARCHAR(191) NOT NULL,
  `trial_session_id` VARCHAR(36) NOT NULL DEFAULT 'prod',
  `transaction_code` VARCHAR(40) NOT NULL,
  `type` ENUM('ASSIGN','BORROW','RETURN','TRANSFER') NOT NULL,
  `asset_id` INT NOT NULL,
  `from_location_id` INT NULL,
  `to_location_id` INT NULL,
  `from_holder_name` VARCHAR(120) NULL,
  `to_holder_name` VARCHAR(120) NULL,
  `transaction_date` DATE NOT NULL,
  `expected_return_date` DATE NULL,
  `actual_return_date` DATE NULL,
  `status` ENUM('ACTIVE','COMPLETED','CANCELLED') NOT NULL DEFAULT 'ACTIVE',
  `note` TEXT NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `ast_tx_owner_trial_code_uidx` (`owner_id`, `trial_session_id`, `transaction_code`),
  INDEX `ast_tx_owner_trial_date_idx` (`owner_id`, `trial_session_id`, `transaction_date`),
  INDEX `ast_tx_asset_idx` (`asset_id`),
  CONSTRAINT `asset_transactions_owner_id_fkey` FOREIGN KEY (`owner_id`) REFERENCES `User`(`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `asset_transactions_asset_id_fkey` FOREIGN KEY (`asset_id`) REFERENCES `assets`(`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `asset_transactions_from_location_id_fkey` FOREIGN KEY (`from_location_id`) REFERENCES `asset_locations`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `asset_transactions_to_location_id_fkey` FOREIGN KEY (`to_location_id`) REFERENCES `asset_locations`(`id`) ON DELETE SET NULL ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

