  CONSTRAINT `assets_location_id_fkey` FOREIGN KEY (`location_id`) REFERENCES `asset_locations`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `assets_department_id_fkey` FOREIGN KEY (`department_id`) REFERENCES `asset_departments`(`id`) ON DELETE SET NULL ON UPDATE CASCADE
