  `asset_code` VARCHAR(40) NOT NULL,
  `asset_name` VARCHAR(200) NOT NULL,
  `category_id` INT NULL,
  `brand` VARCHAR(120) NULL,
  `model` VARCHAR(160) NULL,
  `serial_number` VARCHAR(160) NULL,
  `description` TEXT NULL,
